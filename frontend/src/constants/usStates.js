// Helper function to convert state name to state code
export const getStateCode = (stateName) => {
  if (!stateName) return '';
  // If it's already a 2-letter code, return it
  if (stateName.length === 2 && /^[A-Z]{2}$/.test(stateName)) {
    return stateName;
  }
  // Find the state code by matching the label
  const state = US_STATES.find(s => s.label === stateName);
  return state ? state.value : stateName;
};

// Helper function to convert state code to state name
export const getStateName = (stateCode) => {
  if (!stateCode) return '';
  // If it's already a full name, return it
  if (stateCode.length > 2) {
    return stateCode;
  }
  // Find the state name by matching the value
  const state = US_STATES.find(s => s.value === stateCode);
  return state ? state.label : stateCode;
};

